'use client'

import * as React from 'react'
import { ArrowDownRight, ArrowUpRight, CircleHelp, Compass, ShieldAlert, Star } from 'lucide-react'
import { cn } from '@/lib/utils'
import type { Insight } from '@/lib/insights'
import { Popover, PopoverContent, PopoverTrigger } from '@/components/ui/overlay'
import { IconChip, Pill } from '@/components/ui/primitives'

const META: Record<Insight['type'], { icon: typeof Star; tone: 'success' | 'danger' | 'warning' | 'brand' | 'info'; label: string }> = {
  STRENGTH: { icon: Star, tone: 'success', label: 'Strength' },
  IMPROVED: { icon: ArrowUpRight, tone: 'info', label: 'Improved' },
  NEEDS_ATTENTION: { icon: ShieldAlert, tone: 'danger', label: 'Needs attention' },
  DECLINED: { icon: ArrowDownRight, tone: 'warning', label: 'Declined' },
  SUGGESTED_FOCUS: { icon: Compass, tone: 'brand', label: 'Suggested focus' },
}

const RULE_TEXT: Record<string, string> = {
  'R-STRONG': 'Shown when a subject scores at or above the strength threshold in at least two comparable assessments.',
  'R-LOW': 'Shown when a subject is below the low-marks threshold in repeated comparable assessments.',
  'R-SUBJECT-DECLINE': 'Shown when the percentage drops by the decline threshold between consecutive comparable assessments.',
  'R-SUBJECT-IMPROVE': 'Shown when the percentage rises by the decline threshold between consecutive comparable assessments.',
  'R-FAIL': 'Shown when a subject result is recorded as Fail.',
  'R-SGPA-DROP': 'Shown when SGPA falls by the configured amount between two consecutive semesters.',
  'R-SGPA-RISE': 'Shown when SGPA rises by the configured amount between two consecutive semesters.',
  'R-FOCUS': 'Suggested only from subjects that need attention or declined.',
}

export function InsightCard({ insight }: { insight: Insight }) {
  const m = META[insight.type]
  return (
    <li className="rounded-[16px] bg-surface p-4 shadow-1">
      <div className="flex items-start gap-3">
        <IconChip icon={m.icon} tone={m.tone} size="sm" />
        <div className="min-w-0 flex-1">
          <div className="flex flex-wrap items-center gap-2">
            {insight.subject && <span className="text-sm font-semibold text-ink-900">{insight.subject.name}</span>}
            <Pill tone={m.tone === 'brand' ? 'brand' : m.tone}>{m.label}</Pill>
          </div>
          <p className="mt-1.5 text-sm text-ink-700">{insight.message}</p>
          <Popover>
            <PopoverTrigger asChild>
              <button type="button" className="mt-2 inline-flex min-h-8 items-center gap-1.5 text-xs font-medium text-primary-600 hover:underline">
                <CircleHelp className="size-3.5" /> Why am I seeing this?
              </button>
            </PopoverTrigger>
            <PopoverContent align="start" className="w-80">
              <p className="eyebrow">Evidence</p>
              <dl className="mt-2 space-y-1.5 text-sm">
                {insight.evidence.map((e, i) => (
                  <div key={i} className="flex items-baseline justify-between gap-3">
                    <dt className="text-ink-500">{e.label}</dt>
                    <dd className="num text-right text-ink-900">{e.value}</dd>
                  </div>
                ))}
              </dl>
              <p className="mt-3 border-t border-line pt-3 text-xs text-ink-500">
                {RULE_TEXT[insight.ruleId] ?? 'Generated by a transparent rule.'} Rule {insight.ruleId} · confidence {insight.confidence.toLowerCase()}.
              </p>
            </PopoverContent>
          </Popover>
        </div>
      </div>
    </li>
  )
}

export function InsightGroup({ title, description, insights, empty, tile = 'blue', className }: { title: string; description: string; insights: Insight[]; empty: string; tile?: 'blue' | 'green' | 'rose'; className?: string }) {
  return (
    <section aria-label={title} className={cn('min-w-0 rounded-[20px] p-4', { blue: 'bg-tile-blue', green: 'bg-tile-green', rose: 'bg-tile-rose' }[tile], className)}>
      <h3 className="text-sm font-semibold text-ink-900">
        {title} <span className="num ml-1 text-ink-500">{insights.length}</span>
      </h3>
      <p className="mt-0.5 text-xs text-ink-700">{description}</p>
      {insights.length ? (
        <ul className="mt-3 space-y-3">
          {insights.map((i) => (
            <InsightCard key={i.id} insight={i} />
          ))}
        </ul>
      ) : (
        <p className="mt-3 rounded-[16px] bg-surface/70 px-4 py-5 text-center text-sm text-ink-700">{empty}</p>
      )}
    </section>
  )
}
