import { describe, expect, it } from 'vitest'
import { writeFileSync } from 'node:fs'
import { createClient } from '@supabase/supabase-js'
import type { Database } from '@/types/database'

/**
 * MB-05 policy lint: fails when a policy grants HOD access without a branch condition, or a public table has RLS off.
 * Also regenerates tests/rls/policy-inventory.md (table, command, using, with check).
 */
const admin = createClient<Database>(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.SUPABASE_SERVICE_ROLE_KEY!, { auth: { persistSession: false } })

// Any of these in the same policy ties an is_hod() check to the HOD's own branch (or to their own rows).
const BRANCH_SCOPED = /hod_department|current_department|can_manage_department|can_read_department|is_hod_of|created_by = \( SELECT auth\.uid\(\)/

describe('policy lint', () => {
  it('every policy that trusts is_hod() is branch-scoped, and RLS is on for every public table', async () => {
    const { data: policies, error } = await admin.rpc('policy_inventory')
    expect(error).toBeNull()
    const { data: noRls } = await admin.rpc('tables_without_rls')
    expect((noRls ?? []).map((t) => t.tablename)).toEqual([])

    const offenders = (policies ?? []).filter((p) => {
      const text = `${p.qual ?? ''} ${p.with_check ?? ''}`
      return /is_hod\(\)/.test(text) && !BRANCH_SCOPED.test(text)
    })
    expect(offenders.map((p) => `${p.tablename}.${p.policyname}`)).toEqual([])

    const md = [
      '# RLS policy inventory',
      '',
      'Generated by `tests/rls/policy-lint.test.ts` from `pg_policies` (public + storage). Do not edit by hand.',
      '',
      '| Table | Policy | Command | Using | With check |',
      '|---|---|---|---|---|',
      ...(policies ?? []).map((p) => `| ${p.schemaname}.${p.tablename} | ${p.policyname} | ${p.cmd} | \`${(p.qual ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|')}\` | \`${(p.with_check ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|')}\` |`),
    ].join('\n')
    writeFileSync('tests/rls/policy-inventory.md', md + '\n')
  })

  it('the Principal has no write policy on student-data tables', async () => {
    const { data: policies } = await admin.rpc('policy_inventory')
    const studentTables = ['academic_semesters', 'student_subject_results', 'semester_summaries', 'mentor_recommendations', 'mentor_assignments', 'record_change_requests', 'learning_resources', 'mentoring_sessions', 'student_profiles', 'ai_summaries']
    const writes = (policies ?? []).filter((p) => studentTables.includes(p.tablename) && p.cmd !== 'SELECT' && /is_principal/.test(`${p.qual} ${p.with_check}`))
    expect(writes.map((p) => `${p.tablename}.${p.policyname}`)).toEqual([])
  })
})
